import { fireEvent, render, screen, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { I18nProvider } from '@/i18n'
import { VacancyEditor } from '@/features/vacancies/VacancyEditor'
import { vacancyFixtures } from '@/features/vacancies/fixtures'
const entry = { id: 'city', slug: 'city', name: 'Москва', active: true, version: 1, updatedAt: '' }
const dictionaries = { cities: [entry], industries: [{ ...entry, id: 'industry', name: 'IT' }] }
beforeEach(() => { Object.defineProperty(global.crypto, 'randomUUID', { configurable: true, value: jest.fn(() => 'abc-123') }) })
afterEach(() => jest.restoreAllMocks())
it('filters and selects existing names without creating another record', async () => {
  const user = userEvent.setup()
  render(<I18nProvider locale="ru"><VacancyEditor dictionaries={dictionaries} onSave={jest.fn()} onCancel={jest.fn()} /></I18nProvider>)
  await user.click(screen.getByRole('button', { name: 'Город' }))
  await user.type(screen.getByRole('combobox', { name: 'Поиск: Город' }), '  мОСКВА  ')
  expect(screen.queryByRole('option', { name: /Добавить/ })).not.toBeInTheDocument()
  await user.keyboard('{ArrowDown}{Enter}')
  expect(screen.getByRole('button', { name: 'Город' })).toHaveTextContent('Москва')
  expect(screen.queryByRole('listbox')).not.toBeInTheDocument()
})
it('creates through POST and verified GET, selects the result and retains unsaved prose', async () => {
  const user = userEvent.setup()
  const created = { ...entry, id: 'new-city', name: 'Казань' }
  const fetchMock = global.fetch = jest.fn().mockResolvedValueOnce({ ok: true, json: async () => ({ item: created }) } as Response).mockResolvedValueOnce({ ok: true, json: async () => ({ items: [entry, created] }) } as Response)
  render(<I18nProvider locale="ru"><VacancyEditor dictionaries={dictionaries} onSave={jest.fn()} onCancel={jest.fn()} /></I18nProvider>)
  await user.type(screen.getByLabelText('Название вакансии'), 'Несохранённая вакансия')
  await user.click(screen.getByRole('button', { name: 'Город' }))
  await user.type(screen.getByRole('combobox', { name: 'Поиск: Город' }), 'Казань')
  await user.click(screen.getByRole('option', { name: '+ Добавить «Казань»' }))
  await waitFor(() => expect(screen.getByRole('button', { name: 'Город' })).toHaveTextContent('Казань'))
  expect(fetchMock).toHaveBeenCalledTimes(2)
  const request = JSON.parse(fetchMock.mock.calls[0][1]?.body as string)
  expect(request).toEqual({ name: 'Казань', active: true, slug: expect.stringMatching(/^[a-z0-9]+(?:-[a-z0-9]+)*$/) })
  expect(screen.getByLabelText('Название вакансии')).toHaveValue('Несохранённая вакансия')
  await user.click(screen.getByRole('button', { name: 'Город' }))
  expect(screen.getByRole('option', { name: 'Казань' })).toBeInTheDocument()
})

it('retains the name and prose on failure, guards duplicate submissions and permits retry', async () => {
  const user = userEvent.setup()
  let reject!: (error: Error) => void
  const request = new Promise<Response>((_resolve, fail) => { reject = fail })
  const fetchMock = global.fetch = jest.fn().mockReturnValueOnce(request)
  render(<I18nProvider locale="en"><VacancyEditor dictionaries={dictionaries} onSave={jest.fn()} onCancel={jest.fn()} /></I18nProvider>)
  await user.type(screen.getByLabelText('About the role'), 'Keep my description')
  await user.click(screen.getByRole('button', { name: 'Industry' }))
  await user.type(screen.getByRole('combobox', { name: 'Search: Industry' }), 'Robotics')
  const add = screen.getByRole('option', { name: '+ Add «Robotics»' })
  fireEvent.click(add); fireEvent.click(add)
  expect(fetchMock).toHaveBeenCalledTimes(1)
  expect(screen.getByRole('button', { name: 'Save' })).toBeDisabled()
  reject(new Error('offline'))
  expect(await screen.findByRole('alert')).toHaveTextContent('Your entered name is retained')
  expect(screen.getByRole('combobox', { name: 'Search: Industry' })).toHaveValue('Robotics')
  expect(screen.getByLabelText('About the role')).toHaveValue('Keep my description')
  fetchMock.mockRejectedValueOnce(new Error('still offline'))
  await user.click(add)
  expect(fetchMock).toHaveBeenCalledTimes(2)
})
it('shows inactive matches as unavailable rather than creating a duplicate', async () => {
  const user = userEvent.setup()
  render(<I18nProvider locale="en"><VacancyEditor vacancy={{ ...vacancyFixtures[0], cityId: entry.id }} dictionaries={{ ...dictionaries, cities: [{ ...entry, active: false }] }} onSave={jest.fn()} onCancel={jest.fn()} /></I18nProvider>)
  expect(screen.getByRole('button', { name: 'City' })).toHaveTextContent('Москва (Inactive)')
  await user.click(screen.getByRole('button', { name: 'City' }))
  await user.type(screen.getByRole('combobox', { name: 'Search: City' }), ' москва ')
  expect(screen.getByRole('option', { name: /Unavailable for selection/ })).toHaveAttribute('aria-disabled', 'true')
  expect(screen.queryByRole('option', { name: /Add/ })).not.toBeInTheDocument()
  await user.keyboard('{Escape}')
  expect(screen.getByRole('button', { name: 'City' })).toHaveFocus()
  await user.click(screen.getByRole('button', { name: 'City' }))
  await user.tab()
  expect(screen.queryByRole('listbox')).not.toBeInTheDocument()
  await user.click(screen.getByRole('button', { name: 'City' }))
  await user.click(screen.getByLabelText('Company'))
  expect(screen.queryByRole('listbox')).not.toBeInTheDocument()
})

it('keeps a failed creation query when the dropdown is reopened', async () => {
  const user = userEvent.setup()
  global.fetch = jest.fn().mockRejectedValue(new Error('offline'))
  render(<I18nProvider locale="en"><VacancyEditor dictionaries={dictionaries} onSave={jest.fn()} onCancel={jest.fn()} /></I18nProvider>)
  await user.click(screen.getByRole('button', { name: 'City' }))
  await user.type(screen.getByRole('combobox', { name: 'Search: City' }), 'New city')
  await user.keyboard('{Enter}')
  await screen.findByRole('alert')
  await user.keyboard('{Escape}')
  await user.click(screen.getByRole('button', { name: 'City' }))
  expect(screen.getByRole('combobox', { name: 'Search: City' })).toHaveValue('New city')
  expect(screen.getByRole('alert')).toBeInTheDocument()
})
it('starts ArrowUp at the last option and maintains an active descendant', async () => {
  const user = userEvent.setup()
  render(<I18nProvider locale="en"><VacancyEditor dictionaries={{ ...dictionaries, cities: [entry, { ...entry, id: 'last', name: 'Last city' }] }} onSave={jest.fn()} onCancel={jest.fn()} /></I18nProvider>)
  await user.click(screen.getByRole('button', { name: 'City' }))
  await user.keyboard('{ArrowUp}')
  expect(screen.getByRole('combobox', { name: 'Search: City' })).toHaveAttribute('aria-activedescendant', screen.getByRole('option', { name: 'Last city' }).id)
  await user.keyboard('{Enter}')
  expect(screen.getByRole('button', { name: 'City' })).toHaveTextContent('Last city')
})
