#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$ROOT"
ENV_FILE="$ROOT/infra/local/.env"
if [ ! -f "$ENV_FILE" ]; then
  python3 - "$ENV_FILE" <<'PY'
import os, secrets, sys
fd = os.open(sys.argv[1], os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
with os.fdopen(fd, 'w') as f:
    for key in ['LOCAL_DB_PASSWORD', 'LOCAL_JWT_SECRET', 'LOCAL_API_TOKEN']:
        f.write(f'{key}={secrets.token_hex(32)}\n')
    f.write('LOCAL_RUNTIME_IMAGE=openmentor-backend:dev-b759084\n')
PY
fi
set -a
# shellcheck disable=SC1090 # generated private environment, not a source file
source "$ENV_FILE"
set +a
compose() { docker compose --env-file "$ENV_FILE" -f "$ROOT/infra/local/compose.yml" "$@"; }
case "${1:-start}" in
  stop) compose stop backend postgres storage; exit ;;
  status) compose ps; exit ;;
  start|backend) ;;
  *) printf 'Usage: %s [start|backend|stop|status]\n' "$0"; exit 2 ;;
esac
docker info >/dev/null
if ! docker image inspect "$LOCAL_RUNTIME_IMAGE" >/dev/null 2>&1; then
  docker build -t "$LOCAL_RUNTIME_IMAGE" "$ROOT/api"
fi
ARCH="$(docker image inspect "$LOCAL_RUNTIME_IMAGE" --format '{{.Architecture}}')"
(cd api && CGO_ENABLED=0 GOOS=linux GOARCH="$ARCH" go build -o bin/local-api ./cmd/api && CGO_ENABLED=0 GOOS=linux GOARCH="$ARCH" go build -o bin/local-migrate ./cmd/migrate)
compose config -q
compose up -d --build --wait postgres storage
compose run --rm migrate
compose exec -T postgres psql -v ON_ERROR_STOP=1 -U openmentor_local -d openmentor_local < "$ROOT/infra/local/seed.sql"
compose exec -T postgres psql -v ON_ERROR_STOP=1 -U openmentor_local -d openmentor_local < "$ROOT/infra/local/vacancies-seed.sql"
compose exec -T postgres psql -v ON_ERROR_STOP=1 -U openmentor_local -d openmentor_local < "$ROOT/infra/local/research-seed.sql"
compose up -d --wait --no-deps --force-recreate backend
if [ "${1:-start}" = backend ]; then exit; fi
cd web
if [ ! -d node_modules ]; then npm ci --no-audit --no-fund; fi
export APP_ENV=development NEXT_PUBLIC_APP_ENV=development
export NEXT_PUBLIC_GO_API_URL=http://127.0.0.1:18081 GO_API_INTERNAL_TOKEN="$LOCAL_API_TOKEN"
export NEXT_PUBLIC_ANALYTICS_PROVIDER=none NEXT_PUBLIC_POSTHOG_KEY='' NEXT_PUBLIC_FARO_COLLECTOR_URL=''
export O11Y_EXPORTER_ENDPOINT='' NEXT_PUBLIC_TURNSTILE_SITE_KEY=1x00000000000000000000AA
# Optional, isolated Umami integration generated by its local setup.
if [ -f "$ROOT/infra/local/umami/web.env" ]; then
  set -a
  source "$ROOT/infra/local/umami/web.env"
  set +a
fi
printf '\nLocal development: http://localhost:3100/dev\n'
exec npm run dev -- --hostname 127.0.0.1 --port 3100
